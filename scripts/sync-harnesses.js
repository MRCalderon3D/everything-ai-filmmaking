#!/usr/bin/env node
'use strict';
/**
 * sync-harnesses.js — regenerate the harness wrapper directories
 * (.claude/ .codex/ .cursor/ .opencode/ .agents/) from the source layers
 * (commands/, agents/, skills/, rules/, hooks/hooks.json) per
 * manifests/harnesses.json.
 *
 * Idempotent and deterministic: stable ordering, LF endings, and a
 * "GENERATED" header on every emitted file, so scripts/validate.js can diff
 * the directories byte-for-byte.
 */

const path = require('path');
const fs = require('fs');
const { ROOT, walk, readText, readJson, writeFileEnsuring, toPosix, listDirs, exists } = require('./lib/fsx');
const { parseFrontmatter } = require('./lib/md');
const { parseArgs, helpIfRequested } = require('./lib/cli');

const HEADER = 'GENERATED by scripts/sync-harnesses.js — do not edit';

const HELP = `
sync-harnesses.js — regenerate .claude/ .codex/ .cursor/ .opencode/ .agents/

Usage:
  node scripts/sync-harnesses.js [--check] [--root <dir>]

Options:
  --check       Do not write; print drift between disk and what would be
                generated, exit 1 when they differ.
  --root <dir>  Scaffold root (default: this repository).
  --help        Show this help.

Source of truth: commands/*.md, agents/*.md, skills/*/SKILL.md, rules/**,
hooks/hooks.json, and manifests/harnesses.json. Never hand-edit the
generated directories.
`;

function lf(text) {
  let s = String(text).replace(/\r\n/g, '\n');
  if (!s.endsWith('\n')) s += '\n';
  return s;
}

/** Insert the GENERATED header into a markdown doc (after frontmatter). */
function mdWithHeader(content) {
  const src = lf(content);
  const comment = `<!-- ${HEADER} -->\n`;
  if (src.startsWith('---\n')) {
    const end = src.indexOf('\n---', 4);
    if (end !== -1) {
      const afterIdx = src.indexOf('\n', end + 1);
      const head = src.slice(0, afterIdx + 1);
      return head + comment + src.slice(afterIdx + 1);
    }
  }
  return comment + src;
}

/** Strip frontmatter, keep body, prepend header. */
function mdStripped(content) {
  const { body } = parseFrontmatter(content);
  return `<!-- ${HEADER} -->\n` + lf(body);
}

function jsonWithHeader(obj) {
  return lf(JSON.stringify(Object.assign({ $generated: HEADER }, obj), null, 2));
}

/** Collect source documents. Missing dirs yield empty lists. */
function collectSources(root) {
  const sources = { commands: [], agents: [], skills: [], rules: [] };
  const isDoc = (f) => f.endsWith('.md') && path.basename(f).toLowerCase() !== 'readme.md';
  for (const file of walk(path.join(root, 'commands'), { filter: isDoc })) {
    sources.commands.push({ name: path.basename(file, '.md'), file });
  }
  for (const file of walk(path.join(root, 'agents'), { filter: isDoc })) {
    sources.agents.push({ name: path.basename(file, '.md'), file });
  }
  for (const name of listDirs(path.join(root, 'skills'))) {
    const file = path.join(root, 'skills', name, 'SKILL.md');
    if (exists(file)) sources.skills.push({ name, file });
  }
  for (const file of walk(path.join(root, 'rules'), { filter: (f) => f.endsWith('.md') })) {
    const rel = path.relative(path.join(root, 'rules'), file);
    const parts = toPosix(rel).split('/');
    if (path.basename(file).toLowerCase() === 'readme.md') continue;
    sources.rules.push({
      layer: parts.length > 1 ? parts[0] : '',
      name: path.basename(file, '.md'),
      file,
    });
  }
  return sources;
}

/** Claude Code settings.json hook wiring derived from hooks/hooks.json. */
function buildClaudeSettings(hooksConfig) {
  const pre = [];
  const post = [];
  const byMatcher = (list, matcher) => {
    let entry = list.find((e) => e.matcher === matcher);
    if (!entry) {
      entry = { matcher, hooks: [] };
      list.push(entry);
    }
    return entry;
  };
  for (const hook of (hooksConfig && hooksConfig.hooks) || []) {
    const command = `node ${toPosix(hook.script)}`;
    if (hook.event === 'before-file-write') {
      byMatcher(pre, 'Write|Edit').hooks.push({ type: 'command', command });
    } else if (hook.event === 'after-file-write') {
      byMatcher(post, 'Write|Edit').hooks.push({ type: 'command', command });
    } else if (hook.event === 'before-shell-command') {
      byMatcher(pre, 'Bash').hooks.push({ type: 'command', command });
    }
  }
  const settings = { hooks: {} };
  if (pre.length) settings.hooks.PreToolUse = pre;
  if (post.length) settings.hooks.PostToolUse = post;
  return settings;
}

function cursorRuleMdc(rule, content, alwaysApplyLayers) {
  const { frontmatter, body } = parseFrontmatter(content);
  const title = (body.match(/^#\s+(.+)$/m) || [null, rule.name])[1].trim();
  const description = (frontmatter && frontmatter.description) ||
    `${title} — ${rule.layer || 'general'} rule for the AI filmmaking scaffold.`;
  const alwaysApply = (alwaysApplyLayers || []).includes(rule.layer);
  const fm = [
    '---',
    `description: ${JSON.stringify(description)}`,
    `alwaysApply: ${alwaysApply}`,
    '---',
    `<!-- ${HEADER} -->`,
    '',
  ].join('\n');
  return fm + '\n' + lf(body);
}

function codexPointer(sources) {
  const lines = [
    `<!-- ${HEADER} -->`,
    '# Codex configuration for everything-ai-filmmaking',
    '',
    'The root `AGENTS.md` carries the project instructions. Prompts in',
    '`.codex/prompts/` are generated from `commands/*.md` — invoke them as',
    'custom prompts; never edit them here.',
    '',
    '## Available prompts',
    '',
  ];
  for (const cmd of sources.commands) {
    lines.push(`- ${cmd.name}`);
  }
  if (!sources.commands.length) lines.push('- (none generated yet)');
  lines.push('');
  return lines.join('\n');
}

/**
 * Compute the full generation plan: { '<relPath>': '<content>' } with
 * forward-slash relative paths. Pure with respect to output state.
 */
function buildPlan(root = ROOT) {
  const plan = {};
  const harnessManifestFile = path.join(root, 'manifests', 'harnesses.json');
  if (!exists(harnessManifestFile)) return plan;
  const harnesses = readJson(harnessManifestFile).harnesses || [];
  const sources = collectSources(root);
  const hooksFile = path.join(root, 'hooks', 'hooks.json');
  const hooksConfig = exists(hooksFile) ? readJson(hooksFile) : null;

  for (const h of harnesses) {
    const t = h.targetDir;
    if (h.commands) {
      const strip = h.commands.frontmatter === 'strip';
      for (const cmd of sources.commands) {
        const content = readText(cmd.file);
        plan[`${t}/${h.commands.dir}/${cmd.name}${h.commands.extension || '.md'}`] =
          strip ? mdStripped(content) : mdWithHeader(content);
      }
    }
    if (h.agents) {
      const strip = h.agents.frontmatter === 'strip';
      for (const agent of sources.agents) {
        const content = readText(agent.file);
        plan[`${t}/${h.agents.dir}/${agent.name}${h.agents.extension || '.md'}`] =
          strip ? mdStripped(content) : mdWithHeader(content);
      }
    }
    if (h.skills) {
      for (const skill of sources.skills) {
        plan[`${t}/${h.skills.dir}/${skill.name}/SKILL.md`] = mdWithHeader(readText(skill.file));
      }
    }
    if (h.rules) {
      for (const rule of sources.rules) {
        const base = rule.layer ? `${rule.layer}-${rule.name}` : rule.name;
        plan[`${t}/${h.rules.dir}/${base}${h.rules.extension || '.mdc'}`] =
          cursorRuleMdc(rule, readText(rule.file), h.rules.alwaysApplyLayers);
      }
    }
    if (h.settings && hooksConfig) {
      plan[`${t}/${h.settings.file}`] = jsonWithHeader(buildClaudeSettings(hooksConfig));
    }
    if (h.pointer) {
      plan[`${t}/${h.pointer.file}`] = codexPointer(sources);
    }
  }
  return plan;
}

/** Directories/files each harness manages (for stale-file cleanup + drift). */
function managedRoots(root = ROOT) {
  const file = path.join(root, 'manifests', 'harnesses.json');
  if (!exists(file)) return [];
  const roots = [];
  for (const h of readJson(file).harnesses || []) {
    for (const key of ['commands', 'agents', 'skills', 'rules']) {
      if (h[key]) roots.push(`${h.targetDir}/${h[key].dir}`);
    }
    if (h.settings) roots.push(`${h.targetDir}/${h.settings.file}`);
    if (h.pointer) roots.push(`${h.targetDir}/${h.pointer.file}`);
  }
  return roots.sort();
}

/** Compare the plan against disk. Returns list of drift strings. */
function diffPlan(root = ROOT, plan = null) {
  plan = plan || buildPlan(root);
  const drift = [];
  for (const [rel, content] of Object.entries(plan)) {
    const abs = path.join(root, ...rel.split('/'));
    if (!fs.existsSync(abs)) {
      drift.push(`missing: ${rel}`);
      continue;
    }
    const onDisk = readText(abs).replace(/\r\n/g, '\n');
    if (onDisk !== content) drift.push(`stale: ${rel}`);
  }
  // extra files inside managed roots
  const planned = new Set(Object.keys(plan));
  for (const rel of managedRoots(root)) {
    const abs = path.join(root, ...rel.split('/'));
    if (!fs.existsSync(abs)) continue;
    if (fs.statSync(abs).isFile()) {
      if (!planned.has(rel)) drift.push(`unexpected: ${rel}`);
      continue;
    }
    for (const file of walk(abs)) {
      const fileRel = toPosix(path.relative(root, file));
      if (!planned.has(fileRel)) drift.push(`unexpected: ${fileRel}`);
    }
  }
  return drift.sort();
}

function writePlan(root = ROOT, plan = null) {
  plan = plan || buildPlan(root);
  const planned = new Set(Object.keys(plan));
  let written = 0;
  let removed = 0;
  for (const [rel, content] of Object.entries(plan)) {
    const abs = path.join(root, ...rel.split('/'));
    const current = fs.existsSync(abs) ? readText(abs).replace(/\r\n/g, '\n') : null;
    if (current !== content) {
      writeFileEnsuring(abs, content);
      written++;
    }
  }
  for (const rel of managedRoots(root)) {
    const abs = path.join(root, ...rel.split('/'));
    if (!fs.existsSync(abs) || fs.statSync(abs).isFile()) continue;
    for (const file of walk(abs)) {
      const fileRel = toPosix(path.relative(root, file));
      if (!planned.has(fileRel)) {
        fs.unlinkSync(file);
        removed++;
      }
    }
  }
  return { total: Object.keys(plan).length, written, removed };
}

function main() {
  helpIfRequested(process.argv.slice(2), HELP);
  const { flags } = parseArgs();
  const root = flags.root ? path.resolve(String(flags.root)) : ROOT;
  const plan = buildPlan(root);
  if (!Object.keys(plan).length) {
    console.log('sync-harnesses: nothing to generate (missing manifests/harnesses.json or empty sources).');
    process.exit(flags.check ? 1 : 0);
  }
  if (flags.check) {
    const drift = diffPlan(root, plan);
    if (drift.length) {
      console.log(`sync-harnesses --check: ${drift.length} file(s) drifted:`);
      for (const d of drift) console.log(`  ${d}`);
      console.log('Run "npm run sync:harnesses" to regenerate.');
      process.exit(1);
    }
    console.log(`sync-harnesses --check: ${Object.keys(plan).length} generated files up to date.`);
    process.exit(0);
  }
  const result = writePlan(root, plan);
  console.log(`sync-harnesses: ${result.total} files planned, ${result.written} written, ${result.removed} stale removed.`);
}

module.exports = { buildPlan, diffPlan, writePlan, managedRoots, HEADER };

if (require.main === module) main();
